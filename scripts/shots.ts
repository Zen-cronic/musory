// Screenshots of the room and guest pages, with console errors, for a quick visual check.
import { chromium } from "playwright";
const BASE = process.env.BASE || "http://localhost:4377";
const OUT = process.argv[2] || ".cache/shots";
const browser = await chromium.launch({ channel: process.env.PW_CHANNEL || "chrome" });
const errors: string[] = [];
const room = await browser.newPage({ viewport: { width: 1280, height: 720 } });
room.on("console", (m) => m.type() === "error" && errors.push(`room: ${m.text()}`));
room.on("pageerror", (e) => errors.push(`room: ${e.message}`));
await room.goto(`${BASE}/room/copper?film=1`);
await room.waitForTimeout(1500);
const phone = await browser.newPage({ viewport: { width: 390, height: 844 } });
phone.on("console", (m) => m.type() === "error" && errors.push(`phone: ${m.text()}`));
phone.on("pageerror", (e) => errors.push(`phone: ${e.message}`));
const guest = `g-shot${Date.now() % 100000}`;
await phone.goto(`${BASE}/join?venue=copper&as=${guest}`);
await phone.waitForTimeout(800);
await phone.screenshot({ path: `${OUT}/phone-consent.png` });
await phone.click("#checkin");
await phone.waitForTimeout(1200);
await phone.click('[data-sample="t13"]');
await phone.waitForTimeout(400);
await phone.click('[data-sample="t17"]');
await phone.waitForTimeout(2500);
await phone.screenshot({ path: `${OUT}/phone-main.png`, fullPage: true });
await room.screenshot({ path: `${OUT}/room-after-taps.png` });
await phone.click("#forget");
await phone.click("#forget-yes");
await phone.waitForTimeout(4500);
await phone.screenshot({ path: `${OUT}/phone-receipt.png`, fullPage: true });
await room.screenshot({ path: `${OUT}/room-receipt.png` });
console.log("errors:", errors.length ? errors : "none");
await browser.close();
