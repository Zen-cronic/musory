// Browser checks of the guest and room pages (system Chrome via Playwright).
import { chromium } from "playwright";
const BASE = process.env.BASE || "http://localhost:4377";
const OUT = process.argv[2] || ".cache/shots";
let fails = 0;
const check = (name: string, ok: boolean, detail = "") => {
  if (!ok) fails++;
  console.log(`${ok ? "PASS" : "FAIL"} ${name}${detail ? ` (${detail})` : ""}`);
};
const browser = await chromium.launch({ channel: process.env.PW_CHANNEL || "chrome" });
const errors: string[] = [];
const phone = await browser.newPage({ viewport: { width: 390, height: 844 } });
phone.on("pageerror", (e) => errors.push(e.message));
const guest = `e2e-${Date.now() % 100000}`;
await phone.goto(`${BASE}/join?venue=copper&as=${guest}`);
await phone.waitForSelector("#consent:not(.hidden)");
check("consent sheet shows for a new guest", true);
await phone.click("#checkin");
await phone.waitForSelector("#main:not(.hidden)");
check("checked in at Copper Bar", (await phone.textContent("#venue-name")) === "Copper Bar");
await phone.click('[data-sample="t13"]');
await phone.waitForTimeout(600);
check("Forget me is visible after check-in", await phone.isVisible("#forget"));
await phone.click("#switch-venue");
await phone.waitForTimeout(1500);
check("after switching, the page follows the guest to Pulse Club", (await phone.textContent("#venue-name")) === "Pulse Club");
check("after switching, no check-in sheet", !(await phone.isVisible("#consent")));
check("after switching, Forget me is still visible", await phone.isVisible("#forget"));
await phone.screenshot({ path: `${OUT}/e2e-phone-basement.png`, fullPage: true });
await phone.click("#forget");
await phone.click("#forget-yes");
await phone.waitForSelector("#receipt:not(.hidden)", { timeout: 10000 });
check("forget me shows the receipt ending in 0", /→ 0/.test((await phone.textContent("#receipt-count")) ?? ""));
const room = await browser.newPage({ viewport: { width: 1280, height: 720 } });
room.on("pageerror", (e) => errors.push(e.message));
await room.goto(`${BASE}/room/copper?film=1`);
await room.waitForTimeout(1500);
check("room page shows now playing", Boolean(await room.getAttribute("#now-title", "data-track-id")));
check("no page errors", errors.length === 0, errors.join("; "));
await browser.close();
process.exit(fails ? 1 : 0);
